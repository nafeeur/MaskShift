// Kitty "Unicode placeholder" images.
//
// The classic Kitty graphics protocol paints an image as an overlay that floats above the text
// grid. The terminal, not MaskShift, decides when it goes away, and that is where ghosts and
// vanishing pictures come from: a placement that outlives the cells under it after a pane or
// window switch, a repaint that erases it, a modal opened over it.
//
// A placeholder image has no overlay at all. The pixels are transmitted once under an id, and the
// picture is then drawn *as text*: each cell is U+10EEEE followed by two combining marks naming
// its row and column, coloured so the foreground encodes the id. The terminal paints the right
// slice of the image into every such cell. Because the image is ordinary cell content it scrolls,
// clips, is overwritten by a modal and is cleared by a repaint exactly like any other character,
// and the screen's normal diffing keeps it correct with no separate lifecycle to get wrong.
// Supported by Kitty (0.28+) and Ghostty.
//
// https://sw.kovidgoyal.net/kitty/graphics-protocol/#unicode-placeholders

