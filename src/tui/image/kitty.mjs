export const MAX_PLACEHOLDER_CELLS = DIACRITICS.length;

/** A stable 24-bit id (never 0) for an image, so the same picture is only transmitted once. */
export function imageIdFor(key) {
  const digest = crypto.createHash('sha1').update(String(key)).digest();
  const id = ((digest[0] << 16) | (digest[1] << 8) | digest[2]) & 0xffffff;
  return id === 0 ? 1 : id;
}

/** Transmit PNG bytes under `id` and create the virtual placement the placeholder cells refer to. */
export function transmitEscape(id, png, cols, rows) {
  const base64 = Buffer.from(png).toString('base64');
  const chunks = [];
  for (let offset = 0; offset < base64.length; offset += KITTY_CHUNK) chunks.push(base64.slice(offset, offset + KITTY_CHUNK));
  // q=2: never answer. A reply would arrive on stdin and be read as keystrokes.
  let out = '';
  chunks.forEach((chunk, index) => {
    const last = index === chunks.length - 1;
    const control = index === 0 ? `a=t,f=100,i=${id},q=2,m=${last ? 0 : 1}` : `m=${last ? 0 : 1}`;
    out += `${ESC}_G${control};${chunk}${ESC}\\`;
  });
  out += `${ESC}_Ga=p,U=1,i=${id},c=${cols},r=${rows},q=2${ESC}\\`;
  return out;
}

/** Forget an image and free its data in the terminal. */
export function deleteEscape(id) {
  return `${ESC}_Ga=d,d=I,i=${id},q=2${ESC}\\`;
}

/** Delete every image this program transmitted. */
export const DELETE_ALL = `${ESC}_Ga=d,d=A,q=2${ESC}\\`;

/** The text rows that show the image: one string per row, `cols` placeholder cells each. */
export function placeholderRows(id, cols, rows) {
  const colour = `${ESC}[38;2;${(id >> 16) & 255};${(id >> 8) & 255};${id & 255}m`;
  const out = [];
  for (let row = 0; row < rows; row += 1) {
    let line = colour;
    const rowMark = String.fromCodePoint(DIACRITICS[row]);
    for (let col = 0; col < cols; col += 1) line += PLACEHOLDER + rowMark + String.fromCodePoint(DIACRITICS[col]);
    out.push(`${line}${ESC}[39m`);
  }
  return out;
}
